//! Hand-drawn 10×20 glyphs for currency signs outside ISO 8859-1/-15.
//! Each row is 10 bits, MSB = leftmost column.

macro_rules! g {
    ($($row:literal)*) => {{
        const fn row(s: &str) -> u16 {
            let b = s.as_bytes();
            let mut v = 0u16;
            let mut i = 0;
            while i < 10 {
                v = (v << 1) | if b[i] == b'#' { 1 } else { 0 };
                i += 1;
            }
            v
        }
        [$(row($row)),*]
    }};
}

pub type Glyph = [u16; 20];

