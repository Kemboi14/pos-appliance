pub fn glyph(c: char) -> &'static Glyph {
    match c {
        '₹' => &INR,
        '₦' => &NGN,
        '₱' => &PHP,
        '₽' => &RUB,
        '₺' => &TRY,
        '₩' => &KRW,
        _ => &UNKNOWN,
    }
}
